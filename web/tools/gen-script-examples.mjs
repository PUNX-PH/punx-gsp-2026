// Copies the example games (unity/runner-template/Assets/Runner/Tests/Scripts/*.lua, which the Unity tests play) into web/src/lib/script/examples.ts, because
// the website is built from the web folder alone and the prompt carries some of them whole. A test (examples.test.ts) fails when the two differ.
// Usage, from web/: node tools/gen-script-examples.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "..", "..", "unity", "runner-template", "Assets", "Runner", "Tests", "Scripts");
const target = join(here, "..", "src", "lib", "script", "examples.ts");

const escape = (text) => text.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");

const names = readdirSync(source)
  .filter((f) => f.endsWith(".lua"))
  .map((f) => f.slice(0, -4))
  .sort();

const body = names
  .map((name) => `  ${name}: \`${escape(readFileSync(join(source, `${name}.lua`), "utf8").replace(/\r\n/g, "\n"))}\`,`)
  .join("\n");

writeFileSync(
  target,
  `// Generated by tools/gen-script-examples.mjs from unity/runner-template/Assets/Runner/Tests/Scripts/*.lua: do not edit by hand.
// The example games the Unity tests play, as text, for the prompt (prompts.ts) and for the checks (examples.test.ts keeps this equal to the files).
export const EXAMPLE_GAMES: Readonly<Record<string, string>> = {
${body}
};
`,
);
console.log(`wrote ${names.length} examples: ${names.join(", ")}`);
